#!/usr/bin/env python3
"""Purpose: Generate a deterministic index of the bot's documented major modules.

Responsibilities:
- Resolve the canonical architecture manifest's existing covered source paths.
- Extract human-authored purpose statements from parsed Python module docstrings.
- Produce or validate docs/MODULE_INDEX.md without maintaining duplicate metadata.

Boundaries: Read-only source analysis; never import production trading modules.
Safety: Check mode does not change files; write mode updates only the generated page.
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

from scripts import module_doc_guard

MANIFEST = Path("docs/architecture/agent_manifest.json")
INDEX = Path("docs/MODULE_INDEX.md")
BT = chr(96)


def module_group(path: str) -> str:
    """Group a covered file by its existing source directory."""
    prefix = "src/nifty_scalper_bot/"
    if path.startswith(prefix):
        remainder = path[len(prefix) :]
        if "/" not in remainder:
            return prefix
        return prefix + remainder.split("/", 1)[0] + "/"
    return path.split("/", 1)[0] + "/"


def summary(source: str) -> str:
    """Take a real module-docstring purpose without importing executable code."""
    docstring = ast.get_docstring(ast.parse(source))
    if not docstring:
        raise ValueError("Missing Python module docstring")
    for line in docstring.splitlines():
        candidate = line.strip()
        if not candidate or candidate.lower() in {"purpose:", "file purpose:"}:
            continue
        for prefix in ("File purpose:", "Purpose:"):
            if candidate.lower().startswith(prefix.lower()):
                candidate = candidate[len(prefix) :].strip()
        if candidate:
            return candidate.replace("|", r"\|").replace(BT, "\\" + BT)
    raise ValueError("Opening module docstring contains no purpose statement")


def render(root: Path) -> str:
    """Render source-derived navigational Markdown in stable group/path order."""
    payload = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    paths = sorted(
        module_doc_guard.covered_modules(payload),
        key=lambda path: (module_group(path), path),
    )
    lines = [
        "# Critical module index (generated)",
        "",
        f"<!-- Generated by {BT}python -m scripts.module_index --write{BT}; "
        "do not edit manually. -->",
        "",
        "This navigation index is derived from the authoritative "
        "[architecture manifest](architecture/agent_manifest.json) and each "
        "module's opening docstring. It does not define runtime ownership or "
        "replace [the trading lifecycle](TRADING_LIFECYCLE.md).",
        "",
        f"**Documented critical modules:** {len(paths)}",
        "",
    ]
    group: str | None = None
    for path in paths:
        file = root / path
        if not file.is_file():
            raise FileNotFoundError(f"Manifest references missing module: {path}")
        new_group = module_group(path)
        if new_group != group:
            if group is not None:
                lines.append("")
            lines.extend(
                [
                    f"## {BT}{new_group}{BT}",
                    "",
                    "| Module | Purpose at a glance |",
                    "| --- | --- |",
                ]
            )
            group = new_group
        purpose = summary(file.read_text(encoding="utf-8"))
        lines.append(f"| [{BT}{Path(path).name}{BT}](../{path}) | {purpose} |")
    return "\n".join(lines) + "\n"


def is_current(root: Path) -> bool:
    """Check that a checked-in catalog exactly matches current canonical sources."""
    target = root / INDEX
    return target.is_file() and target.read_text(encoding="utf-8") == render(root)


def main(argv: list[str] | None = None) -> int:
    """Check, write, or print the source-derived index."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check", action="store_true", help="Fail on stale/missing index"
    )
    mode.add_argument(
        "--write", action="store_true", help="Regenerate checked-in index"
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        generated = render(root)
        if args.check:
            if not is_current(root):
                print(
                    "MODULE_INDEX is stale/missing; run "
                    "python -m scripts.module_index --write",
                    file=sys.stderr,
                )
                return 1
            print("Generated module index is up to date")
            return 0
        if args.write:
            target = root / INDEX
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(generated, encoding="utf-8")
            print(f"Wrote {target.relative_to(root)}")
            return 0
        sys.stdout.write(generated)
        return 0
    except (OSError, ValueError, SyntaxError, json.JSONDecodeError) as exc:
        print(f"MODULE_INDEX: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
